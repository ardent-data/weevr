"""Warps resolved at load reach the executor, end to end through ``Context.run``."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
from pyspark.sql import SparkSession

from weevr.context import Context

pytestmark = pytest.mark.spark

WARP = """config_version: "1.0"
columns:
  - name: id
    type: bigint
  - name: name
    type: string
  - name: region
    type: string
    default: "n/a"
"""


def _write(path: Path, body: dict[str, Any] | str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body if isinstance(body, str) else json.dumps(body))


def _thread(src: str, target: dict[str, Any]) -> dict[str, Any]:
    return {
        "config_version": "1.0",
        "sources": {"main": {"type": "delta", "alias": src}},
        "target": target,
        "write": {"mode": "append"},
    }


class TestAliasTargetWarp:
    """The documented alias + warp config applies the warp, whatever the cwd."""

    def test_alias_target_with_explicit_warp(
        self,
        spark: SparkSession,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
        request: pytest.FixtureRequest,
    ):
        src = str(tmp_path / "src")
        spark.createDataFrame([(1, "a")], ["id", "name"]).write.format("delta").save(src)
        # Own location so the database never lands in the default warehouse
        spark.sql(f"CREATE DATABASE b028_warp LOCATION '{tmp_path / 'b028_warp.db'}'")
        request.addfinalizer(lambda: spark.sql("DROP DATABASE IF EXISTS b028_warp CASCADE"))
        # Alias overwrite is unavailable on OSS Spark >= 3.5.6, so pre-create and append
        spark.sql(
            "CREATE TABLE b028_warp.dim_customer (id BIGINT, name STRING, region STRING) "
            "USING delta"
        )
        project = tmp_path / "p.weevr"
        _write(project / "threads" / "dim_customer.warp", WARP)
        _write(
            project / "threads" / "dim_customer.thread",
            _thread(src, {"alias": "b028_warp.dim_customer", "warp": "dim_customer"}),
        )
        monkeypatch.chdir(tmp_path)  # neither the project nor the thread directory

        result = Context(spark=spark, project=str(project)).run("threads/dim_customer.thread")

        assert result.status == "success", result.detail
        rows = spark.table("b028_warp.dim_customer").collect()
        assert [(r.id, r.name, r.region) for r in rows] == [(1, "a", "n/a")]


class TestWarpDiscovery:
    """A warp named after the target applies without target.warp."""

    def test_discovered_warp_appends_warp_only_column(self, spark: SparkSession, tmp_path: Path):
        src = str(tmp_path / "src")
        spark.createDataFrame([(1, "a")], ["id", "name"]).write.format("delta").save(src)
        target = str(tmp_path / "Tables" / "dim_customer")
        project = tmp_path / "p.weevr"
        _write(project / "dim_customer.warp", WARP)
        thread = _thread(src, {"path": target})
        thread["write"] = {"mode": "overwrite"}
        _write(project / "dim_customer.thread", thread)

        result = Context(spark=spark, project=str(project)).run("dim_customer.thread")

        assert result.status == "success", result.detail
        rows = spark.read.format("delta").load(target).collect()
        assert [(r.id, r.name, r.region) for r in rows] == [(1, "a", "n/a")]

    def test_opt_out_ignores_matching_warp(self, spark: SparkSession, tmp_path: Path):
        src = str(tmp_path / "src")
        spark.createDataFrame([(1, "a")], ["id", "name"]).write.format("delta").save(src)
        target = str(tmp_path / "Tables" / "dim_customer")
        project = tmp_path / "p.weevr"
        _write(project / "dim_customer.warp", WARP)
        thread = _thread(src, {"path": target, "warp": False})
        thread["write"] = {"mode": "overwrite"}
        _write(project / "dim_customer.thread", thread)

        result = Context(spark=spark, project=str(project)).run("dim_customer.thread")

        assert result.status == "success", result.detail
        assert spark.read.format("delta").load(target).columns == ["id", "name"]


class TestAutoGeneratedWarpDestination:
    """warp_mode: auto writes where the next load will look."""

    @staticmethod
    def _project(spark: SparkSession, tmp_path: Path) -> tuple[str, str, Path]:
        src = str(tmp_path / "src")
        spark.createDataFrame([(1, "a")], ["id", "name"]).write.format("delta").save(src)
        return src, str(tmp_path / "Tables" / "dim_customer"), tmp_path / "p.weevr"

    def test_creates_target_named_warp_beside_thread_file(
        self, spark: SparkSession, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ):
        src, target, project = self._project(spark, tmp_path)
        thread = _thread(src, {"path": target, "warp_mode": "auto"})
        thread["write"] = {"mode": "overwrite"}
        _write(project / "threads" / "load_customers.thread", thread)
        cwd = tmp_path / "elsewhere"
        cwd.mkdir()
        monkeypatch.chdir(cwd)

        result = Context(spark=spark, project=str(project)).run("threads/load_customers.thread")

        assert result.status == "success", result.detail
        assert (project / "threads" / "dim_customer.warp").exists()
        assert not list(cwd.iterdir())
        assert not (tmp_path / "Tables" / "dim_customer.warp").exists()
        # The generated warp is discovered on the next load
        rerun = Context(spark=spark, project=str(project)).run("threads/load_customers.thread")
        assert rerun.status == "success", rerun.detail

    def test_updates_the_loaded_warp_in_place(self, spark: SparkSession, tmp_path: Path):
        src, target, project = self._project(spark, tmp_path)
        _write(project / "warps" / "customers.warp", WARP)
        thread = _thread(src, {"path": target, "warp": "warps/customers", "warp_mode": "auto"})
        thread["write"] = {"mode": "overwrite"}
        _write(project / "threads" / "load_customers.thread", thread)

        result = Context(spark=spark, project=str(project)).run("threads/load_customers.thread")

        assert result.status == "success", result.detail
        text = (project / "warps" / "customers.warp").read_text()
        assert "auto_generated: true" in text
        assert not (project / "threads" / "dim_customer.warp").exists()


class TestAutoGeneratedWarpRemoteProject:
    """A thread loaded from a non-local project skips auto-generation with a warning."""

    def test_skips_and_warns(
        self, spark: SparkSession, tmp_path: Path, caplog: pytest.LogCaptureFixture
    ):
        import logging
        from unittest.mock import patch

        from weevr.engine.executor import execute_thread
        from weevr.model.thread import Thread
        from weevr.model.warp import WarpBinding

        target = str(tmp_path / "Tables" / "dim_customer")
        thread = Thread.model_validate(
            {
                "name": "load_customers",
                "config_version": "1.0",
                "sources": {"src": {"type": "delta", "alias": "src_table"}},
                "target": {"path": target, "warp_mode": "auto"},
            }
        )
        remote_dir = "abfss://ws@onelake.dfs.fabric.microsoft.com/lh/Files/p.weevr"
        thread.bind_warp(
            WarpBinding(warp=None, warp_file=None, thread_dir=remote_dir, writable=False)
        )
        df = spark.createDataFrame([(1, "a")], ["id", "name"])
        with (
            patch("weevr.engine.executor.read_source", side_effect=lambda *a, **k: df),
            patch("weevr.engine.executor.auto_generate_warp") as auto_gen,
            caplog.at_level(logging.WARNING, logger="weevr.engine.executor"),
        ):
            result = execute_thread(spark, thread)

        assert result.status == "success"
        auto_gen.assert_not_called()
        assert any("load_customers" in m and "warp" in m for m in caplog.messages)
